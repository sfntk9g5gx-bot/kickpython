# Считаем буквы и порядок появления
letters_dict, order = count_letters(main_str)

# Считаем частоты
frequency_dict = calculate_frequency(letters_dict)

# Выводим частоты в порядке появления букв в тексте
for letter in order:
    print(f"{letter}: {frequency_dict[letter]:.2f}")